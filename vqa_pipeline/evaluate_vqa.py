def _video_duration_seconds(video_path: Path) -> float:
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration",
         "-of", "default=noprint_wrappers=1:nokey=1", str(video_path)],
        check=True, capture_output=True, text=True,
    )
    return float(out.stdout.strip())


def format_duration(seconds: float) -> str:
    minutes = round(seconds / 60)
    return f"{minutes} minutes ({int(round(seconds))} seconds)"


def _extract_clip(video_path: Path, start: float, end: float, out_path: Path, fps: float,
                   scale_width: int | None = STAGE_VIDEO_SCALE_WIDTH, crf: int = STAGE1_CRF) -> None:
    """Encodes at `fps` and (optionally) downscaled to `scale_width` — the fps passed to Gemini's
    video_metadata only controls how it *samples* whatever bytes it receives, and it applies
    MEDIA_RESOLUTION_LOW regardless; neither shrinks the file, so we downsample both frame rate
    and resolution here (native 1080p at native rate would be multi-GB).

    NOTE: `ffmpeg -ss` re-zeroes the output's timeline (frame at original `start` becomes 0s).
    For the stage2/3 shared clip we therefore pass start=0 and exclude the intro via Gemini's
    VideoMetadata.start_offset instead, so the model keeps ORIGINAL video time (verified: with
    start_offset the model still timestamps events in original coordinates)."""
    vf = f"fps={fps}"
    if scale_width is not None:
        vf += f",scale={scale_width}:-2"
    subprocess.run(
        ["ffmpeg", "-y", "-ss", f"{start:.3f}", "-i", str(video_path), "-t", f"{end - start:.3f}",
         "-an", "-vf", vf, "-c:v", "libx264", "-preset", "veryfast", "-crf", str(crf), str(out_path)],
        check=True, capture_output=True,
    )


def categories_of(ann: dict) -> list[str]:
    cat = ann.get("category")
    return cat if isinstance(cat, list) else [cat]


def load_action_goal_transcript(label_annotations: dict, include_action: bool = True,
                                  include_goal: bool = True) -> list[dict]:
    wanted = ({"ACTION"} if include_action else set()) | ({"GOAL"} if include_goal else set())
    items = [
        {"start": a["start"], "end": a["end"], "transcript_text": a.get("transcript_text", "")}
        for a in label_annotations["annotations"]
        if wanted & set(categories_of(a))
    ]
    items.sort(key=lambda i: i["start"])
    return items


_TXT_TRANSCRIPT_LINE = re.compile(r"^\[(\d+):(\d{2}):(\d{2}(?:\.\d+)?)\]\s*(.*)$")


def load_raw_transcript(dataset_dir: Path, label_annotations: dict) -> list[dict]:
    """Loads the literal source transcript that label_annotations.json's categorized spans were
    built from — every line, regardless of category — from <dataset>/transcripts/<transcript_file>
    (named by label_annotations.json's "transcript_file" field). Handles both forms seen across
    datasets: JSON (a list of {id, start, end, text, speaker, ...}) and plain text ("[H:MM:SS.mmm]
    text" per line, start only, no end)."""
    path = dataset_dir / "transcripts" / label_annotations["transcript_file"]
    if path.suffix == ".json":
        entries = [{"start": r["start"], "end": r["end"], "transcript_text": r["text"]}
                   for r in json.loads(path.read_text())]
    else:
        entries = []
        for line in path.read_text().splitlines():
            m = _TXT_TRANSCRIPT_LINE.match(line)
            if not m:
                continue
            h, minutes, seconds, text = m.groups()
            start = int(h) * 3600 + int(minutes) * 60 + float(seconds)
            entries.append({"start": start, "transcript_text": text})
    entries.sort(key=lambda e: e["start"])
    return entries


def filtered_context(entries: list[dict], reference_end: float | None, drop_timestamps: bool = False) -> str:
    """reference_end=None means no cutoff (stage2/3's full history). drop_timestamps strips the
    start/end fields after filtering (used for the --no-timestamps full-context setting) — the
    cutoff still applies first, using the timestamps, before they're removed from the output."""
    relevant = entries if reference_end is None else [e for e in entries if e["start"] < reference_end]
    if drop_timestamps:
        relevant = [{k: v for k, v in e.items() if k not in ("start", "end")} for e in relevant]
    return json.dumps(relevant, indent=2)


def timestamps_only_context(entries: list[dict]) -> str:
    """Ground-truth spans with the action/state DESCRIPTIONS stripped — just the bare timespans.
    Used for the stage2/3 (timestamp-answer) judge context so the model can't answer by looking
    up the described action's timestamp in the sheet; it must use the video to determine what
    happens at each candidate time. (stage1 keeps full descriptions — its answers are prose, not
    timestamp lookups, so there's no leak.)"""
    return json.dumps([f"{int(round(e['start']))}s-{int(round(e['end']))}s" for e in entries], indent=2)


def build_choices(item: dict) -> tuple[str, dict[str, str], str]:
    """Shuffle correct + incorrect answers deterministically per item, letter them A/B/C/...
    Returns (choices_block_text, {letter: answer_text}, correct_letter)."""
    incorrect = [v for k, v in item.items() if re.fullmatch(r"incorrect_answer\d+", k)]
    options = [(True, item["correct_answer"])] + [(False, v) for v in incorrect]
    rng = random.Random(f"{item['annotation_id']}:{item['stage']}")
    rng.shuffle(options)
    letters = list(string.ascii_uppercase[: len(options)])
    letter_map = {}
    correct_letter = None
    lines = []
    for letter, (is_correct, text) in zip(letters, options):
        letter_map[letter] = text
        lines.append(f"{letter}) {text}")
        if is_correct:
            correct_letter = letter
    return "\n".join(lines), letter_map, correct_letter


def load_output(output_file: Path, dataset: str, model: str) -> dict:
    if output_file.exists():
        return json.loads(output_file.read_text())
    return {"dataset": dataset, "model": model, "generated_at": None, "results": []}


def save_output(output_file: Path, output: dict) -> None:
    output["generated_at"] = datetime.now(timezone.utc).isoformat()
    output_file.write_text(json.dumps(output, indent=2))


def hard_keys_from_blind(dataset_dir: Path) -> set[str]:
    """--hard-only support: "annotation_id:stage" keys wrong in AT LEAST ONE of the
    dataset's blind runs (the temp=0 baseline plus any temp!=0 repeat passes sitting
    alongside it — see scoring.blind_run_paths). A 3-run repeat check found only
    ~33% of items were wrong in every run while another ~15% flipped right/wrong
    depending on which single run was used, so pooling across every run found (rather
    than trusting just the baseline) is required to not undercount the hard set — see
    hard_items.py for the full variance analysis. An item that never parsed
    to a letter in any run is excluded — neither hard nor easy — same convention
    scoring.blind_wrongness uses."""
    from scoring import blind_run_paths, blind_wrongness

    if not blind_run_paths(dataset_dir):
        sys.exit(f"--hard-only needs a blind run first: no eval_results_no_video_no_text*.json "
                  f"found under {dataset_dir} (run with --no-video --no-text)")
    by_key, _ = blind_wrongness(dataset_dir)
    return {key for key, entry in by_key.items() if entry["wrong"]}


