"""
Evaluate <dataset>/vqa.json's multiple-choice questions against a Gemini judge model.

For each vqa.json item, builds:
  - a ground_truth_actions.json text context
  - a transcript text context: only label_annotations.json entries tagged ACTION or GOAL,
    reduced to just {start, end, transcript_text}
  - a video clip
  - the multiple-choice answers, shuffled per item (deterministic seed) and lettered A/B/C/...

Per-stage context scope (mirrors how each question type's context was built when it was
generated by query_gemini_annotations.py):
  - stage1 (all 4 target categories): ground_truth_actions and the ACTION/GOAL transcript are
    both cut off at the source annotation's reference_end (same cutoff stage1 generation
    used); video is that item's original narrow ~30s clip (from gemini_queries.json's
    video_window, floored to VIDEO_FLOOR_SECONDS), sampled at 1fps. Nothing here is shared
    across items, so each stage1 call sends its context/video fresh, uncached.
  - stage2 (PLAN) and stage3 (ASSESSMENT): the transcript is the FULL history, but the
    ground-truth actions are sent as TIMESTAMPS ONLY (descriptions withheld) so the model can't
    answer these timestamp questions by looking the action up in the sheet — it must use the
    video to determine what happens at each candidate time. Video is one shared clip of the
    whole recording (encoded from 0s at STAGE23_FPS, downscaled), with the pre-VIDEO_FLOOR intro
    excluded via VideoMetadata.start_offset rather than by cutting — so the model perceives
    events in ORIGINAL video time, matching the timestamp answers (verified: with start_offset
    the model timestamps events in original coordinates, so no label shifting is needed). This
    shared video clip — identical across every stage2/3 item and, more importantly, across
    every eval setting that keeps the same video encoding — is cached ONCE in a Vertex AI
    CachedContent and referenced by every stage2/3 call. The text context (ground_truth/
    transcript) is deliberately kept OUT of that cache and sent inline on every call instead:
    unlike the video, it changes with nearly every baseline flag combination, and re-bundling it
    into the cache key would force a full cache rebuild (re-encoding + re-uploading the whole
    video) on every such change just to swap out its cheap, small part. With --no-cache the video
    is sent inline too (no Vertex caching at all), for validating the basic flow. Stage2 questions
    describe "the current point" (e.g. "the experimenter is currently increasing the stirring
    speed") without stating it, and since the history above is sent uncut, nothing else pins that
    moment down — so each stage2 item's vqa.json current_point (build_vqa.py's carry-through of
    Gemini's own future_event identification from stage2 generation) is stated as text, always,
    regardless of --no-video.
  - interview (prose "why" answers, same shape as stage1): text context is the SAME full-history
    pipeline stage2/3 use (ground_truth_actions + the ACTION/GOAL-or-raw transcript) — every
    baseline flag (--no-action/--no-goal/--no-ground-truth/--no-timestamps/--raw-transcript, plus
    --no-video/--only-video/--no-text) applies to it exactly as it does for stage2/3. Video is the
    WHOLE reference video, one shared Vertex CachedContent across every interview item — reusing
    the exact cache query_gemini_annotations.py --interview and generate_adversarial_grounded.py
    already built (same key format, so a default-model run hits it instead of re-encoding) —
    since a cached video's own metadata can't be overridden per call, each item's
    [reference_start, reference_end] (read from interview_queries.json) is instead stated as text
    in the prompt whenever video is sent.

The context (video clip + ground-truth actions + transcript) is ALWAYS delivered as separate
Parts — inline for stage1, text always inline for stage2/3, video inline under --no-cache or via
the cache otherwise — never embedded in the prompt string. PROMPT_TEMPLATE is therefore a
placeholder that receives only {question} and {choices_block} (a lettered "A) ...\nB) ..."
block); fill in the actual judge-model prompt there.

Answer choices are shuffled with a per-item deterministic seed (annotation_id + stage) so
reruns are reproducible, and labeled A/B/C/...; the correct letter is recorded in the output
for scoring — it is never revealed to the model.

Output is written incrementally to <dataset>/eval_results.json, keyed by "annotation_id:stage"
so re-running skips items already evaluated.

--no-video runs a no-video baseline instead: no video is sent at all (only the same per-stage
text context), writing to <dataset>/eval_results_no_video.json so it doesn't clobber the
with-video results — for comparing how much accuracy the video itself is contributing.

--no-goal runs a no-goal baseline: the ACTION/GOAL transcript context drops its GOAL-tagged
lines, leaving only ACTION lines, so the model doesn't get the experimenter's stated goals as
text context — for comparing how much accuracy that GOAL context is contributing. Writes to
<dataset>/eval_results_no_goal.json (or eval_results_no_video_no_goal.json if combined with
--no-video) so it doesn't clobber the other variants.

--only-video runs an only-video baseline: the inverse of --no-video — video is sent but NO
textual context at all (no ground_truth_actions, no ACTION/GOAL transcript), so the model must
answer from the video alone. Mutually exclusive with --no-video. Writes to
<dataset>/eval_results_only_video.json.

--no-action drops ACTION-tagged lines from the ACTION/GOAL transcript context, leaving only GOAL
lines (the inverse of --no-goal). Combine with the default (video on) to test "video + GOAL only,
no other transcript". Mutually exclusive with --no-goal (together they'd leave no transcript at
all) and with --only-video (which already drops all text). Adds a _no_action suffix to the output
filename.

--no-text drops ALL textual context regardless of the video setting — a more general form of
--only-video that can combine with --no-video. --no-video + --no-text together is the fully blind
floor: no video, no text, just the question and answer choices (a new PROMPT_TEMPLATE_BLIND is
used for this combo, since neither PROMPT_TEMPLATE_NO_VIDEO nor PROMPT_TEMPLATE_ONLY_VIDEO fits
when both are gone). Mutually exclusive with --only-video/--no-goal/--no-action (all redundant
once all text is dropped). Adds a _no_text suffix to the output filename.

--no-timestamps drops the start/end fields from each transcript entry before it's sent, leaving
only its text — so the model gets what was said but not when, and can't read event timing
directly off the transcript. Ground-truth action timestamps (stage1's descriptions-with-times,
stage2/3's bare candidate timespans) are untouched, since those aren't "the transcript" and
stage2/3 questions require them. Mutually exclusive with --only-video/--no-text (no transcript is
sent in either case, so there'd be nothing to strip timestamps from). Adds a _no_timestamps
suffix to the output filename.

--no-ground-truth drops the ground_truth_actions context entirely (stage1's cutoff descriptions
and stage2/3's timestamps-only list), leaving only the transcript as textual context. Mutually
exclusive with --only-video/--no-text (both already drop this, making it redundant). Adds a
_no_ground_truth suffix to the output filename.

--raw-transcript swaps the transcript source from the ACTION/GOAL-only categorized subset (drawn
from label_annotations.json) to the complete original transcript file that label_annotations.json
itself was generated from (named by its "transcript_file" field, under <dataset>/transcripts/) —
every line, regardless of category, exactly as transcribed. Supports both that file's JSON form
(a list of {id, start, end, text, speaker, ...}) and plain-text form ("[H:MM:SS.mmm] text" per
line, start only, as in session02's transcript). Since the raw transcript has no ACTION/GOAL
categories, this is mutually exclusive with --no-goal/--no-action. Stage1 still truncates it at
the item's reference_end (matching the existing anti-spoiler cutoff); stage2/3 still get the full
history, uncut. Adds a _raw_transcript suffix to the output filename.

--raw-transcript --no-ground-truth (+ --no-timestamps for the no-timestamps variant) is the
"full-context" setting: video + the literal, complete transcript and nothing else. Together with
--only-video (video-only) and --no-video --no-text (blind), it forms the three main evaluation
settings.

Usage:
    python3 vqa_pipeline/evaluate_vqa.py --dataset session01
    python3 vqa_pipeline/evaluate_vqa.py --dataset session01 --stage stage3 --limit 1 --no-cache --max-clip-seconds 120
    python3 vqa_pipeline/evaluate_vqa.py --dataset session01 --no-video
    python3 vqa_pipeline/evaluate_vqa.py --dataset session01 --no-goal
    python3 vqa_pipeline/evaluate_vqa.py --dataset session01 --only-video
    python3 vqa_pipeline/evaluate_vqa.py --dataset session01 --raw-transcript --no-ground-truth --no-timestamps
    python3 vqa_pipeline/evaluate_vqa.py --dataset session01 --only-video --hard-only
"""

