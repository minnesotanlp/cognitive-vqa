    # interview stage: read interview_queries.json for each item's [reference_start, reference_end]
    # (stated as text in the prompt, since the shared whole-video cache can't carry per-item
    # metadata) and the reference video's name. Its text context is the same full-history
    # ground_truth/transcript pipeline stage2/3 uses (see text_context_parts() below), so every
    # context flag (--no-action/--no-goal/--no-ground-truth/--no-timestamps/--raw-transcript) plus
